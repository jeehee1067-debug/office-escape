  function credoLine(n) {
    const L = CREDO.lines || [];
    const i = n > 0 ? n - 1 : L.length + n;
    return String(L[i] || '').replace(/\s+/g, '');
  }

  /** 크레도에서 정답을 자동으로 뽑아낸다. 허용 답안 배열을 돌려준다.
      pick      : [[줄, 글자], ...]  글자 위치는 1부터, 음수면 뒤에서부터 (-1 = 마지막)
      word      : [줄, 단어번호]     그 줄의 n번째 낱말
      count     : '단어'             크레도 전체에서 그 단어가 나온 횟수
      len       : 줄번호             그 줄의 글자 수(띄어쓰기 제외)
      lineCount : true               크레도 전체 줄 수                                */
  function credoAnswers(spec) {
    if (!spec) return [];
    if (spec.pick) {
      const s = spec.pick.map(pair => {
        const t = credoLine(pair[0]);
        const i = pair[1] > 0 ? pair[1] - 1 : t.length + pair[1];
        return t.charAt(i) || '';
      }).join('');
      return s ? [s] : [];
    }
    if (spec.word) {
      const raw = String((CREDO.lines || [])[spec.word[0] - 1] || '').trim().split(/\s+/);
      const w = raw[spec.word[1] - 1] || '';
      return w ? [w] : [];
    }
    if (spec.count) {
      const all = (CREDO.lines || []).join('').replace(/\s+/g, '');
      const n = all.split(spec.count).length - 1;
      return [String(n), n + '번', n + '회'];
    }
    if (spec.len) { const n = credoLine(spec.len).length; return [String(n), n + '자', n + '글자']; }
    if (spec.lineCount) { const n = (CREDO.lines || []).length; return [String(n), n + '줄', n + '개']; }
    return [];
  }

